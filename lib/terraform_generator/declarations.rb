	}
}
        GO
      end

      # Docs examples derive so they cannot drift from the schema:
      # required args only, var-block style; a required parent reference
      # pulls its parent resource in, depth one, so examples stay
      # copy-paste runnable.
      def example_sources(definition)
        out = {}
        base = File.join(Emit.provider_repo, "examples")
        if definition.emitted_kinds.include?(:resource)
          out[File.join(base, "resources", "ubicloud_#{definition.name}", "resource.tf")] =
            resource_example(definition)
        end
        if definition.emitted_kinds.include?(:datasource)
          out[File.join(base, "data-sources", "ubicloud_#{definition.name}", "data-source.tf")] =
            datasource_example(definition)
        end
        out
      end

      EXAMPLE_VARS = <<-TF
variable "project_id" {
  description = "Ubicloud project"
  type        = string
  default     = "pj01qy4sty1j7nycv8hfqmgy6t"
}

variable "location" {
  description = "Ubicloud location"
  type        = string
  default     = "eu-central-h1"
}

      TF

      def example_value(definition, name, parents)
        case name
        when "project_id" then "var.project_id"
        when "location" then "var.location"
        when "name" then "\"example-#{definition.name.to_s.tr("_", "-")}\""
        when "cidr" then "\"10.0.0.0/24\""
        when "size" then "\"standard-2\""
        when "id", /_id\z/ then "\"#{definition.name.to_s[0, 2]}01qy4sty1j7nycv8hfqmgy6t\""
        when "public_key" then "\"ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIEXAMPLEexampleEXAMPLEexampleEXAMPLEexampleEXAM user@example\""
        when /\A(\w+)_reference\z/
          parent = TerraformGenerator[$1.to_sym]
          parents << parent
          "ubicloud_#{parent.name}.example.name"
        else
          raise "#{definition.name}: example needs a value rule for required #{name}"
        end
      end

      def required_args(definition)
        TerraformGenerator::Schema.spec_for(definition, :resource)["schema"]["attributes"]
          .filter_map do |a|
            type = a.keys.reject { it == "name" }.first
            a["name"] if a[type]["computed_optional_required"] == "required"
          end
      end

      def resource_block(definition, label, parents)
        args = required_args(definition).map do |n|
          "  #{n} = #{example_value(definition, n, parents)}"
        end
        "resource \"ubicloud_#{definition.name}\" \"#{label}\" {\n#{args.join("\n")}\n}\n"
      end

      def resource_example(definition)
        parents = []
        body = resource_block(definition, "example", parents)
        parent_bodies = parents.uniq.map { resource_block(it, "example", []) + "\n" }.join
        EXAMPLE_VARS + parent_bodies + body
      end

      def datasource_example(definition)
        _, _, key_pairs = TerraformGenerator::Reflection.attributes_for(definition)
        parents = []
        args = key_pairs.map do |_, attr|
          "  #{attr} = #{example_value(definition, attr.to_s, parents)}"
        end
        pb = parents.uniq.map { resource_block(it, "example", []) + "\n" }.join
        EXAMPLE_VARS + pb +
          "data \"ubicloud_#{definition.name}\" \"example\" {\n#{args.join("\n")}\n}\n"
      end

      # path => rendered content for this definition's declaration files
      # plus the shared plane (component union, registration, runtime,
      # examples); terraform:check byte-compares committed files against
      # exactly this map.
      def sources(definition)
        base = File.join(Emit.provider_repo, "internal", "provider")
        example_sources(definition).merge(
          File.join(base, "provider_gen.go") => provider_source,
          File.join(base, "api_components_gen.go") => shared_components_source,
          File.join(base, "#{definition.name}_gen.go") => gen_source(definition),
          File.join(base, "#{definition.name}_client_gen.go") => client_source(definition),
        )
      end

      # Components are API-global (private_subnet nests firewalls nests
      # rules); one shared file owns every struct across flagged
      # definitions, recomputed deterministically on any generate.
      def shared_components_source
        components = {}
        TerraformGenerator.resources.each_key do |name|
          d = TerraformGenerator[name]
          collect_components(d, Emit::ResourceContext.new(d), components) if d.emitted_kinds.include?(:resource)
          if d.emitted_kinds.include?(:datasource)
            attrs, = kind_attrs(d, :datasource)
            ctx = Emit::DatasourceContext.new(d)
            union!(components, ctx.details_component, attrs)
            attrs.select(&:nested).each { collect_nested_components(it, components) }
          end
        end
        needs_time = components.values.flatten.any? { it.format == "date-time" }
        out = +"// Code generated by clover rake terraform:generate. DO NOT EDIT.\n\npackage provider\n\n"
        out << "import \"time\"\n\n" if needs_time
        out << components.sort.map { |n, a| component_struct(n, a) }.join
      end
    end
  end
